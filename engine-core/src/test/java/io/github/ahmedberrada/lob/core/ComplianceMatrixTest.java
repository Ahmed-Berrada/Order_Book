package io.github.ahmedberrada.lob.core;

import static org.assertj.core.api.Assertions.assertThat;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.TreeSet;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Stream;
import org.junit.jupiter.api.Test;

/**
 * Keeps {@code docs/compliance/rule-matrix.md} equal to what the repository says: every rule of the
 * rulebook, the chapter that defines it, whether it is in force, and the tests that verify it.
 *
 * <p>To regenerate it after changing rules or tests, run the build with {@code -Dlob.regenerate=true}.
 */
class ComplianceMatrixTest {

    private static final Path ROOT = Path.of("..");
    private static final Path RULEBOOK = ROOT.resolve("docs/rulebook");
    private static final Path MATRIX = ROOT.resolve("docs/compliance/rule-matrix.md");
    private static final Pattern RULE = Pattern.compile("\\*\\*([A-Z]{2,4}-\\d{3}): ([^*]+?)\\.\\*\\*");
    private static final Pattern ANNOTATION = Pattern.compile("@Rulebook\\(([^)]*)\\)");
    private static final Pattern RULE_ID = Pattern.compile("\"([A-Z]{2,4}-\\d{3})\"");
    private static final Pattern DECLARATION = Pattern.compile("(?:void|class)\\s+(\\w+)");
    private static final int MAX_TESTS_LISTED = 4;

    private record Rule(String id, String title, String chapter, boolean draft) {
    }

    @Test
    void theMatrixIsUpToDate() throws IOException {
        String expected = render();
        if (Boolean.getBoolean("lob.regenerate")) {
            Files.createDirectories(MATRIX.getParent());
            Files.writeString(MATRIX, expected);
        }
        assertThat(Files.readString(MATRIX))
                .as("docs/compliance/rule-matrix.md is stale: run the build with -Dlob.regenerate=true")
                .isEqualTo(expected);
    }

    @Test
    void everyRuleInForceHasAtLeastOneTestInTheMatrix() throws IOException {
        for (String line : render().lines().filter(l -> l.startsWith("| `")).toList()) {
            if (line.contains("| in force |")) {
                assertThat(line).as("a rule without a test").doesNotContain("| — |");
            }
        }
    }

    private static String render() throws IOException {
        List<Rule> rules = rules();
        Map<String, TreeSet<String>> verifiedBy = verifiers();
        StringBuilder out = new StringBuilder();
        out.append("# Rule matrix\n\n")
                .append("Generated by `ComplianceMatrixTest` from the [rulebook](../rulebook/) and the `@Rulebook` annotations\n")
                .append("of every module's tests. Do not edit by hand: change a rule or a test, then run the build with\n")
                .append("`-Dlob.regenerate=true`. The build fails when this file is stale.\n\n")
                .append("Regulation to rules: [regulatory-mapping.md](regulatory-mapping.md).\n\n");
        long inForce = rules.stream().filter(r -> !r.draft()).count();
        out.append("**").append(rules.size()).append(" rules, ").append(inForce).append(" in force, ")
                .append(rules.size() - inForce).append(" draft.**\n\n")
                .append("| Rule | Title | Chapter | Status | Verified by |\n|---|---|---|---|---|\n");
        for (Rule rule : rules) {
            TreeSet<String> tests = verifiedBy.getOrDefault(rule.id(), new TreeSet<>());
            out.append("| `").append(rule.id()).append("` | ").append(rule.title()).append(" | [")
                    .append(rule.chapter()).append("](../rulebook/").append(rule.chapter()).append(".md) | ")
                    .append(rule.draft() ? "draft" : "in force").append(" | ").append(listed(tests)).append(" |\n");
        }
        return out.toString();
    }

    private static String listed(TreeSet<String> tests) {
        if (tests.isEmpty()) {
            return "—";
        }
        List<String> names = new ArrayList<>(tests);
        String shown = String.join(", ", names.subList(0, Math.min(MAX_TESTS_LISTED, names.size())));
        return names.size() > MAX_TESTS_LISTED ? shown + " and " + (names.size() - MAX_TESTS_LISTED) + " more" : shown;
    }

    private static List<Rule> rules() throws IOException {
        List<Rule> rules = new ArrayList<>();
        try (Stream<Path> files = Files.list(RULEBOOK)) {
            for (Path file : files.filter(p -> p.toString().endsWith(".md")).sorted().toList()) {
                String text = Files.readString(file);
                boolean draft = text.contains("- **Status:** Draft");
                String chapter = file.getFileName().toString().replace(".md", "");
                Matcher matcher = RULE.matcher(text);
                while (matcher.find()) {
                    rules.add(new Rule(matcher.group(1), matcher.group(2).trim(), chapter, draft));
                }
            }
        }
        rules.sort(java.util.Comparator.comparing(Rule::id));
        return rules;
    }

    /** Rule ID to the tests that cite it, as {@code Class#method}, or {@code Class} for a class annotation. */
    private static Map<String, TreeSet<String>> verifiers() throws IOException {
        Map<String, TreeSet<String>> byRule = new TreeMap<>();
        try (Stream<Path> modules = Files.list(ROOT)) {
            for (Path tests : modules.map(m -> m.resolve("src/test/java")).filter(Files::isDirectory).sorted().toList()) {
                try (Stream<Path> files = Files.walk(tests)) {
                    for (Path file : files.filter(p -> p.toString().endsWith(".java")).sorted().toList()) {
                        String text = Files.readString(file);
                        String type = file.getFileName().toString().replace(".java", "");
                        Matcher annotation = ANNOTATION.matcher(text);
                        while (annotation.find()) {
                            Matcher declaration = DECLARATION.matcher(text);
                            if (!declaration.find(annotation.end())) {
                                continue;
                            }
                            String name = declaration.group().startsWith("class") ? type : type + "#" + declaration.group(1);
                            RULE_ID.matcher(annotation.group(1)).results()
                                    .forEach(m -> byRule.computeIfAbsent(m.group(1), k -> new TreeSet<>()).add(name));
                        }
                    }
                }
            }
        }
        return byRule;
    }
}
